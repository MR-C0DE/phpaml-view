<?php
declare(strict_types=1);
require __DIR__ . '/bootstrap.php';

use AML\View\{FileApplication, FunctionalComponent, Renderer, Testing\TestView, Testing\ViewTest};
use AML\View\Tests\Functional\Components\{Counted, Legacy as LegacyClass};
use function AML\View\Tests\Functional\Components\{Broken, Counter, DefaultObject, InvalidReturn, Labels, Legacy, Recursive, Reference};
use function AML\View\Tests\Functional\Last\EmptyRoot;

$source = __DIR__ . '/fixtures/functional';
$app = new FileApplication($source, namespace: 'AML\\View\\Tests\\Functional');
$check = static function (bool $condition, string $message): void { if (!$condition) throw new RuntimeException($message); };
$check($app->paths() === ['/', '/other', '/users/[id]'], 'Function/class routes were not discovered together.');
$check(Counted::$calls === 0, 'Discovery ran a default constructor.');
$html = $app->mount('/')->rootHtml();
$check(Counted::$calls === 1, 'Lazy invocation repeated a default constructor.');
$other = $app->mount('/other')->rootHtml();
if (in_array('--json', $argv, true)) { echo json_encode(['home' => $html, 'other' => $other], JSON_THROW_ON_ERROR); exit; }
$check(str_contains($html, 'Functional home') && str_contains($html, 'labels:one,two') && str_contains($html, 'badge'), 'Functional render is incomplete.');
$check(str_contains($html, $source . '/components'), 'Original __DIR__ was lost.');
$check(str_contains($html, 'rgb(112, 71, 235)'), 'Relative CSS module was lost.');
$check(!str_contains($html, '<body'), 'body() must not create a document body.');
$check(str_contains($html, 'id="shared-layout"'), 'Functional pages lost their class layout.');
$check((new ReflectionFunction(Counter(...)))->getFileName() === $source . '/components/Cards.php', 'Reflection must retain original filenames.');
$check(Legacy() instanceof LegacyClass, 'A handwritten class factory changed behavior.');
$check(Counter() instanceof FunctionalComponent, 'Function calls must be lazy outside rendering too.');
$renderer = new Renderer();
$check($renderer->render(EmptyRoot()) === '', 'Empty body failed.');
$check(str_contains($renderer->render(Labels(last: 'named')), 'labels:named'), 'Named variadic props failed.');
$first = 'a'; $second = 'b'; $last = 'c'; $reference = Reference($first, $second, last: $last);
$check([$first, $second, $last] === ['a', 'b', 'c'], 'A functional body ran during construction.');
$renderer->render($reference);
$check([$first, $second, $last] === ['a!', 'b!', 'c!'], 'PHP parameter references were lost.');
$check(str_contains($app->mount('/users/42?tab=settings')->html(), '42:settings'), 'Dynamic route arguments failed.');
$app->metadata('/');
$check(str_contains($app->head('/other'), 'Class metadata'), 'Class metadata changed.');
$classTest = new TestView($other);
$classTest->click('Change title');
foreach (['title', 'forwarded-title', 'class-title'] as $id) $check(str_contains($classTest->html(), 'id="' . $id . '">Updated</span>'), 'Reactive functional prop failed: ' . $id);
$classTest->fill('title', 'From form')->assertState('title', 'From form');
$test = new TestView($html);
$left = 'components.AML.View.Tests.Functional.Components.Counter.i1.__locals.state1';
$right = 'components.AML.View.Tests.Functional.Components.Counter.i2.__locals.state1';
$test->click('left+')->click('left+')->click('right-')->assertState($left, 2)->assertState($right, 9);
$test->fill('message', 'Edited')->assertState('__locals.state1', 'Edited');
$test->click('Preview')->assertState('__locals.state1', 'Preview');
$test->click('Legacy+')->assertState('components.AML.View.Tests.Functional.Components.Legacy.i1.count', 6);
ViewTest::assertThrows(fn () => $test->click('left-invalid'), TypeError::class, 'State(');
$test->assertState($left, 2);
ViewTest::assertThrows(fn () => Counter(initial: 'bad'), TypeError::class);
ViewTest::assertThrows(fn () => Counter(unknown: 'bad'), Error::class);
ViewTest::assertThrows(fn () => $renderer->render(Broken()), RuntimeException::class, 'functional render failed');
ViewTest::assertThrows(fn () => $renderer->render(Recursive()), RangeException::class, 'nested renders');
ViewTest::assertThrows(fn () => $renderer->render(InvalidReturn()), TypeError::class, 'InvalidReturn');
$check(AML\View\InlineStateRegistry::current() === [] && AML\View\InlineEffectRegistry::current() === [], 'Exceptional render leaked hooks.');
$check($html === $app->mount('/')->rootHtml(), 'Function state leaked across renders.');
$check($html === (new FileApplication($source . '/.', namespace: 'AML\\View\\Tests\\Functional'))->mount('/')->rootHtml(), 'Repeated discovery changed functions.');
$check(!$test->renderErrors(), 'Unexpected reactive render errors.');
echo "Functional views: lazy pages/components, typed/default/named props, State forwarding, class interop, CSS and cleanup passed.\n";
